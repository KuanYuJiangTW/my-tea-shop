-- 為什麼改，一句話版本：
--   萬鷺朝鳳導覽 250 元掉進了「入園費價格帶」——隔壁競品低消 200，
--   客人拿它跟入園費比而不是跟導覽比，比完的結論是「不如自己看」，
--   而旁邊那個免費觀景平台還真的就是我們家的。250 元是在跟自家的
--   免費商品競爭，而且輸定了。
--
--   成本面同樣站不住：材料以 50／人估，250 元、2 人成行的一場淨 400 元，
--   佔用 3 小時（含接待）＝ 133 元／小時，低於現行基本工資時薪。
--   一件不划算的事不會被好好經營——這是調價真正的理由，不是想多賺。
--
-- ⚠ 這是正式營運資料，改完客人看到的價格立刻變。跑之前先確認：
--   1. 目前沒有「已預約未付款」的萬鷺朝鳳導覽（改價不影響已成立的訂單，
--      但客人若在結帳頁停留，重整後會看到新價）
--   2. Sanity 的 admissionTiers 四層價目已同步（否則頁面上會出現
--      「導覽 450」與階梯表寫 250 兩個數字打架）
--
-- 執行：Supabase SQL Editor 整檔貼上跑。可重複執行（冪等）。
-- ============================================================

-- ── 1. 萬鷺朝鳳導覽：250 → 450，成團門檻 4 → 2 ───────────────
--
-- 門檻降到 2 是本季最重要的一項，比價格更關鍵：
--   賞鳥季業主本來就在現場（顧停車、管秩序、賣茶），導覽佔的是
--   「人已經在那裡」的 1.5 小時，增量成本跟「為了採茶專門空出半天」
--   完全是兩回事。4 人門檻擋掉的是一對夫妻、一個帶小孩的家庭、
--   一個扛大砲的攝影客——而這三種正是賞鳥的主力客層。
--   季節第一年，拒絕一個獨行的攝影客等於拒絕一篇會發在賞鳥社團的圖文。
UPDATE experience_types
SET price = 450, min_participants = 2
WHERE slug = 'cattle-egret-tour';

-- ── 2. 紅茶製作：800 → 1,000，成團門檻 4 → 6 ─────────────────
--
-- 六款裡最深的一款（5 小時、業主＋鄰居兩人帶、完整製程、成品帶回），
-- 卻跟茶藝體驗同價。兩個人的時間被佔住就是兩份時間成本，要以「人時」算：
--   4 人 → 2,600 ÷ 10 人時 = 260／人時（比下田還低）
--   6 人 → 3,900 ÷ 10 人時 = 390／人時 ✓
-- 調到 1,000 後 6 人 = 6,000，仍在一般團體預算內。
UPDATE experience_types
SET price = 1000, min_participants = 6
WHERE slug = 'tea-making';

-- ── 3. 其餘四款門檻校正回 2026-08-21 拍板值 ──────────────────
-- 採茶／烤茶／茶藝／茶果酒維持 4 人。線上目前就是 4，這段是防漂移用的，
-- 跑了不會有任何變化；日後若有人手動改過，這裡會把它拉回來。
UPDATE experience_types
SET min_participants = 4
WHERE slug IN ('tea-picking', 'roasted-tea', 'tea-ceremony', 'tea-wine');

-- ── 4. 萬鷺朝鳳半日（若已建立）：門檻 3 ──────────────────────
-- 這一款由 add_egret_half_day.sql 建立，可能還沒跑；沒有就不動，不會報錯。
UPDATE experience_types
SET min_participants = 3
WHERE slug = 'egret-half-day';

-- ── 5. 驗證：跑完應該看到下面這張表 ──────────────────────────
--   萬鷺朝鳳・茶山導覽  450   1.5h  min 2
--   紅茶製作            1000  3h    min 6
--   茶藝體驗            800   2h    min 4
--   烤茶 / 採茶         450   2h    min 4
--   淺漬茶果酒          600   2h    min 4
--   （萬鷺朝鳳半日      650   4h    min 3  ← 只有跑過 add_egret_half_day 才有）
SELECT slug, name, price, duration_hours, min_participants, max_participants, is_active
FROM experience_types
ORDER BY id;
